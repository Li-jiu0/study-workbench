def evidence(frm, n=2):
    ev = []
    for f, tid, txt in ALL:
        p = txt.find(frm)
        if p < 0: continue
        a = max(0, p-16); b = min(len(txt), p+len(frm)+16)
        ev.append("id%s %s ...%s..." % (tid, f, txt[a:b].replace("\n","\\n")))
        if len(ev) >= n: break
    return ev

rules = []
for frm, to, cat in RULES:
    c = count(frm)
    rules.append({"from": frm, "to": to, "count": c, "cat": cat,
                  "evidence": evidence(frm)})

assert all(r["count"] >= 1 for r in rules), [r for r in rules if r["count"] < 1]

