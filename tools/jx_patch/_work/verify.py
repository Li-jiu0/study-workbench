alltext = []
for t in texts:
    alltext.append(("q", t["id"], t["q"]))
    for k, o in enumerate(t["o"] or []):
        alltext.append(("o%d" % k, t["id"], str(o)))

lines = []
for frm, to in CAND:
    n = 0; ev = []
    for field, tid, txt in alltext:
        idx = 0
        while True:
            p = txt.find(frm, idx)
            if p < 0: break
            n += 1
            if len(ev) < 3:
                a = max(0, p-18); b = min(len(txt), p+len(frm)+18)
                ev.append("id=%s %s | %s" % (tid, field, txt[a:b].replace("\n","\\n")))
            idx = p+1
    m = 0
    for field, tid, txt in alltext:
        m += txt.count(to)
    lines.append((n, m, frm, to, ev))

lines.sort(key=lambda x: (-x[0], x[2]))
with io.open(os.path.join(OUT, "verify.txt"), "w", encoding="utf-8") as f:
    for n, m, frm, to, ev in lines:
        flag = "OK " if n >= 1 else "---"
        f.write("[%s] %s -> %s   命中 %d | 目标词现次 %d\n" % (flag, frm, to, n, m))
        for e in ev:
            f.write("        %s\n" % e)
print("done", len(lines))
