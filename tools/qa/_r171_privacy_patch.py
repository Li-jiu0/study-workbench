EDITS.append(('right_5_8', OLD_E, NEW_E))

report = []
fails = []
for name, old, new in EDITS:
    n = s.count(old)
    if n != 1:
        fails.append('%s: 命中 %d 次（应为 1）' % (name, n))
        report.append('  [SKIP] %-11s 命中 %d 次 —— 未替换' % (name, n))
        continue
    s = s.replace(old, new)
    report.append('  [OK]   %-11s 命中 1 次，已替换（+%d 字符）' % (name, len(new) - len(old)))

print('\n'.join(report))
print('FAILS=%s' % (fails or '无'))

if fails:
    print('有未命中项 → 不写盘')
    raise SystemExit(1)

io.open(P, 'w', encoding='utf-8', newline='').write(s)

