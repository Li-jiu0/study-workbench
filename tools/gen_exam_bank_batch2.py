REQUIRED_FIELDS = ("id", "type", "sub", "diff", "q", "o", "a", "x", "tip")


def build_questions(qtype, rows):
    """把 (id, sub, diff, q, o, a, x, tip) 元组转成题目字典列表。"""
    out = []
    for row in rows:
        qid, sub, diff, stem, options, answer, explain, tip = row
        item = {
            "id": qid,
            "type": qtype,
            "sub": sub,
            "diff": diff,
            "q": stem,
            "o": list(options),
            "a": answer,
            "x": explain,
            "tip": tip,
        }
        for field in REQUIRED_FIELDS:
            if field not in item or item[field] is None:
                raise ValueError("题目 %s 缺少字段 %s" % (qid, field))
        if len(item["o"]) != 4:
            raise ValueError("题目 %s 的选项数量不是4个" % qid)
        if not (0 <= item["a"] <= 3):
            raise ValueError("题目 %s 的答案索引越界" % qid)
        out.append(item)
    return out


def write_json(path, payload):
    """以 UTF-8 无 BOM、2 空格缩进写出 JSON。"""
    text = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"
    with io.open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main():
    if not os.path.isdir(DATA_DIR):
        print("【错误】未找到题库目录：%s" % DATA_DIR)
        return 1

    all_ids = []
    total = 0
    for filename, qtype, rows in SHARDS:
        questions = build_questions(qtype, rows)
        all_ids.extend(q["id"] for q in questions)
        total += len(questions)
        payload = {
            "version": VERSION,
            "comment": "行测增量第二批·%s（id 301–400 段位，只 push 不覆盖内置与第一批）" % qtype,
            "questions": questions,
        }
        write_json(os.path.join(DATA_DIR, filename), payload)
        print("【写出】%s  题型=%s  题数=%d  id=%d–%d"
              % (filename, qtype, len(questions),
                 questions[0]["id"], questions[-1]["id"]))

    if len(set(all_ids)) != len(all_ids):
        print("【错误】新分片内部存在重复 id")
        return 1
    print("第二批合计题数：%d，id 范围 %d–%d" % (total, min(all_ids), max(all_ids)))

    with io.open(INDEX_PATH, "r", encoding="utf-8") as f:
        index = json.load(f)

    existing = set(s["file"] for s in index.get("shards", []))
    added = 0
    for filename, qtype, rows in SHARDS:
        rel = "assets/data/" + filename
        if rel in existing:
            print("【跳过】索引中已存在：%s" % rel)
            continue
        index["shards"].append({"file": rel, "type": qtype, "count": len(rows)})
        added += 1

    index["version"] = VERSION
    index["comment"] = ("题库增量分片索引。第一批=内置60+增量140=200题；"
                        "第二批新增100题（id 301–400），合并后总量300题")

    write_json(INDEX_PATH, index)
    print("【更新】索引新增分片 %d 个，当前分片总数 %d 个，version=%s"
          % (added, len(index["shards"]), index["version"]))
    return 0


